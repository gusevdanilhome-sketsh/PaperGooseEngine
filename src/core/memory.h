/**
 * @file memory.h
 * @brief Безопасные обёртки над функциями работы с памятью в стиле MISRA.
 *
 * Все функции проверяют аргументы и завершают программу при невозможности выделить память,
 * т.к. для игрового движка нехватка памяти критична.
 */

#ifndef MEMORY_H
#define MEMORY_H

#include <stddef.h>

/**
 * @brief Выделить блок памяти заданного размера.
 * @param[in] size Размер в байтах.
 * @return Указатель на выделенный блок или NULL в случае ошибки.
 */
void* mem_alloc(size_t size);

/**
 * @brief Освободить ранее выделенный блок памяти.
 * @param[in] ptr Указатель на блок.
 */
void mem_free(void* ptr);

#endif /* MEMORY_H */